// Translate with an explicit Spanish default (for keys not in the table yet).
inline const char* tr(const char* key, const char* es_default) {
    if (!key) return "";
    std::size_t n = 0;
    const Entry* t = table(n);
    for (std::size_t i = 0; i < n; ++i) {
        if (std::strcmp(t[i].key, key) != 0) continue;
        if (state() == Lang::En && t[i].en) return t[i].en;
        if (t[i].es) return t[i].es;
        break;
    }
    return es_default ? es_default : key;
}

inline const char* tr(const char* key) { return tr(key, key); }

