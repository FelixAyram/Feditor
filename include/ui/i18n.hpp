inline const char* tr_lit(const char* es) {
    if (!es) return "";
    if (state() == Lang::Es) return es;
    std::size_t n = 0;
    const LitEntry* t = lit_table(n);
    for (std::size_t i = 0; i < n; ++i)
        if (std::strcmp(t[i].es, es) == 0) return t[i].en;
    return es;
}

